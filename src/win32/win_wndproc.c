/* ---- MapKey  0x00466B70 ----  returns byte: retail's 126 path is `mov al,7Eh` */
byte MapKey( unsigned int uCode, int lParam )
{
  unsigned int key;
  int i;

  if ( ( lParam & 0x00FF0000 ) == 0x00290000 )
  {
    return 126;
  }

  if ( uCode > 0 && uCode <= 0x91 )
  {
    key = s_vkToKey[2 * uCode + ( ( lParam >> 24 ) & 1 )];
    if ( key )
    {
      return (byte) key;
    }
  }

  key = MapVirtualKeyA( uCode, 2 ) & 0xFF;
  if ( key > 0x7F )
  {
    for ( i = 0; s_charFixup[2 * i]; ++i )
    {
      if ( key == s_charFixup[2 * i] )
      {
        key = s_charFixup[2 * i + 1];
        break;
      }
    }
  }
  return (byte) key;
}

