/* 0x008E58C4. The "we have taken Alt-Tab away" latch, so the pair below is idempotent in both directions. */

/* ---- WIN_DisableAltTab  0x00466A30 ---- */
void WIN_DisableAltTab( void ) {
	if ( s_altTabDisabled ) {
		return;
	}

	if ( !Q_stricmp( Cvar_VariableString( "arch" ), "winnt" ) ) {
		RegisterHotKey( NULL, 0, MOD_ALT, VK_TAB );
	} else {
		BOOL old;

		SystemParametersInfoA( SPI_SETSCREENSAVERRUNNING, 1, &old, 0 );
	}
	s_altTabDisabled = 1;
}

/* ---- WIN_EnableAltTab  0x00466AB0 ---- */
void WIN_EnableAltTab( void ) {
	if ( !s_altTabDisabled ) {
		return;
	}

	if ( !Q_stricmp( Cvar_VariableString( "arch" ), "winnt" ) ) {
		UnregisterHotKey( NULL, 0 );
	} else {
		BOOL old;

		SystemParametersInfoA( SPI_SETSCREENSAVERRUNNING, 0, &old, 0 );
	}
	s_altTabDisabled = 0;
}

/* ---- VID_AppActivate  0x00466B20 ----  VERIFIED */
int VID_AppActivate( int fActive, int minimized )
{
  int result;

  g_wv_isMinimized = minimized;
  Key_ClearStates();
  result = 0;
  if ( !fActive || g_wv_isMinimized )
  {
    g_wv_activeApp = 0;
    in_appactive = 0;
    if ( s_wmv_mouseInitialized )
    {
      if ( s_wmv_mouseActive )
      {
        s_wmv_mouseActive = 0;
        return IN_DeactivateWin32Mouse();
      }
    }
  }
  else
  {
    result = 1;
    g_wv_activeApp = 1;
    in_appactive = 1;
  }
  return result;
}

